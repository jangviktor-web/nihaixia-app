def main():
    with open(HERBS_JSON, 'r', encoding='utf-8') as f:
        data = json.load(f)

    updated = 0
    for name, note in TANG_NOTES.items():
        for h in data['herbs']:
            if h['name'] == name:
                existing = h.get('historical_notes', '')
                if not existing or len(note) > len(existing):
                    h['historical_notes'] = note
                    updated += 1
                break

    with open(HERBS_JSON, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Updated historical_notes for {updated} herbs")

if __name__ == '__main__':
    main()
