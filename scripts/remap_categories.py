with open('assets/data/formulas.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

remapped = 0
unmapped = set()
for f in data['formulas']:
    old_cat = f['category']
    if old_cat == '倪海厦经验方' or old_cat == '金疮药':
        continue  # 保留特殊分类
    new_cat = CATEGORY_MAP.get(old_cat)
    if new_cat:
        f['category'] = new_cat
        remapped += 1
    elif old_cat not in unmapped:
        unmapped.add(old_cat)

with open('assets/data/formulas.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print(f"Remapped {remapped} formulas")
if unmapped:
    print(f"Unmapped categories: {unmapped}")

# 统计新分类
from collections import Counter
cats = Counter(f['category'] for f in data['formulas'])
print("\nNew category counts:")
for cat, cnt in sorted(cats.items(), key=lambda x: -x[1]):
    print(f"  {cat}: {cnt}")
