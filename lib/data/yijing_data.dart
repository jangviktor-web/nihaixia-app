/// 八卦（先天八卦数序：乾1 兑2 离3 震4 巽5 坎6 艮7 坤8）
class Trigram {
  final int xiantian; // 先天数 1-8
  final String name; // 乾
  final String nature; // 天
  final String symbol; // ☰
  final List<int> lines; // 下→上，1=阳 0=阴
  const Trigram(this.xiantian, this.name, this.nature, this.symbol, this.lines);
}

