/// 关煞/扩展煞检索：query 为空返回全部；否则按 名称/别名/口诀 逐字段 contains。
/// 若 category 非 null 再叠加 category 相等过滤。返回新列表，不改原列表。
List<GuanshaEntry> searchGuansha(String query, [String? category]) {
  final q = query.trim().toLowerCase();
  final List<GuanshaEntry> all = [...kGuanshaEntries, ...kExtShaEntries];
  Iterable<GuanshaEntry> list = all;
  if (category != null) {
    list = list.where((e) => e.category == category);
  }
  if (q.isEmpty) return list.toList();
  return list.where((e) =>
      e.name.toLowerCase().contains(q) ||
      e.aliases.any((a) => a.toLowerCase().contains(q)) ||
      e.jue.toLowerCase().contains(q)).toList();
}
