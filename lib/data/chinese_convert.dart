/// 逐字符简繁归一：将 [s] 中的繁体字映射为简体，未收录字符原样返回。
/// 为 1:1 字符映射（长度不变），因此可安全用于「归一命中 → 原文位置高亮」。
String toSimplified(String s) {
  if (s.isEmpty) return s;
  final sb = StringBuffer();
  for (var i = 0; i < s.length; i++) {
    final ch = s[i];
    sb.write(kTraditionalToSimplified[ch] ?? ch);
  }
  return sb.toString();
}
