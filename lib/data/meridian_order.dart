/// 表外穴位（非十二正经：督脉 / 任脉 / 经外奇穴 等）在**经络内部**的排序权重。
const int kUnknownPointOrderIndex = 1 << 20;

/// 在 [canon] 中查找 [key]，兼容「国标名带不带尾部『穴』」两种写法。
///
/// 库里的穴名有三种形态：
/// - `中府穴`（带穴，绝大多数）
/// - `地五会`（不带穴）
/// - `气穴`（本身就是 2 字国标名、以「穴」结尾）
/// 因此这里先试原样、再试去尾「穴」、最后试加尾「穴」，三者任一命中即返回下标。
int _indexOfCanonicalName(List<String> canon, String key) {
  var i = canon.indexOf(key);
  if (i >= 0) return i;
  if (key.endsWith('穴')) {
    final stripped = key.substring(0, key.length - 1);
    i = canon.indexOf(stripped);
    if (i >= 0) return i;
    return canon.indexOf('$stripped穴');
  }
  return canon.indexOf('$key穴');
}

/// 穴位名在其所属经络内部的**国标循行下标**；表外穴位返回 [kUnknownPointOrderIndex]。
///
/// 匹配顺序：① 库内写法原样 → ② 去尾「穴」→ ③ 经络内异名 [kPointAlias] 归一。
/// 全部落空（临床组合穴、俗称等）返回 [kUnknownPointOrderIndex]。
int pointOrderIndex(String meridian, String name) {
  final canon = kMeridianPointOrder[meridian];
  if (canon == null) return kUnknownPointOrderIndex;
  final base = name.endsWith('穴') ? name.substring(0, name.length - 1) : name;
  var i = _indexOfCanonicalName(canon, base);
  if (i >= 0) return i;
  final alias = kPointAlias[base];
  if (alias == null) return kUnknownPointOrderIndex;
  return _indexOfCanonicalName(canon, alias);
}
